#!/usr/bin/env python3
"""Convert catalogs/*.json into a single Markdown document of tables.

Default writes docs/catalog.md; pass --check to verify the generated file
is up to date (exit non-zero when stale).
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG_DIR = ROOT / "catalogs"
OUT = ROOT / "docs" / "catalog.md"

COLUMNS = ["path", "name", "branch", "topic", "language", "platform", "protocol", "groups"]


def load_catalogs():
    for catalog_path in sorted(CATALOG_DIR.glob("*.json")):
        data = json.loads(catalog_path.read_text(encoding="utf-8"))
        yield catalog_path.stem, data.get("repositories", [])


def render():
    lines = [
        "# Repository Catalog",
        "",
        "Generated by `tools/catalog_to_markdown.py` from `catalogs/*.json` - do not edit by hand.",
        "",
    ]
    for stem, repos in load_catalogs():
        lines.append(f"## {stem} ({len(repos)} repos)")
        lines.append("")
        lines.append("| " + " | ".join(COLUMNS) + " |")
        lines.append("| " + " | ".join(["---"] * len(COLUMNS)) + " |")
        rows = sorted(repos, key=lambda r: (r.get("topic", ""), r.get("path", "")))
        for r in rows:
            cells = [
                r.get("path", ""),
                r.get("name", ""),
                r.get("branch", ""),
                r.get("topic", ""),
                r.get("language", ""),
                r.get("platform", ""),
                r.get("preferred_protocol", "https"),
                ", ".join(r.get("groups", [])),
            ]
            lines.append("| " + " | ".join(str(c).replace("|", "\\|") for c in cells) + " |")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main():
    ap = argparse.ArgumentParser(description="Convert catalogs/*.json to Markdown tables")
    ap.add_argument("--check", action="store_true",
                    help="verify docs/catalog.md is up to date instead of writing it")
    args = ap.parse_args()
    content = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if content != current:
            sys.exit("docs/catalog.md is out of date; run: python3 tools/catalog_to_markdown.py")
        print("docs/catalog.md is up to date")
        return
    OUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({content.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
