#!/usr/bin/env python3
"""Render catalogs/manifests.xlsx into a Markdown document of tables.

Single source of truth is the Excel workbook (see
docs/DSN-20261128-001-excel-manifest-design.md). Two tables are rendered:
- 自有仓库分类与建议动作: self rows carrying a category
- 清单明细: every repository, grouped by platform then path

Default writes docs/catalog.md; pass --check to verify the generated file
is up to date (exit non-zero when stale).
"""
import argparse
import sys
from pathlib import Path

import generate_manifests as gm

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "catalog.md"

CLASSIFY_COLUMNS = ["path", "标签分类", "仓库属性", "description", "suggested_action"]
DETAIL_COLUMNS = ["path", "name", "branch", "topic", "language", "platform", "groups"]
HEADER = {
    "path": "path", "标签分类": "标签分类", "仓库属性": "仓库属性",
    "description": "描述", "suggested_action": "建议动作",
    "name": "name", "branch": "branch", "topic": "topic",
    "language": "language", "platform": "platform", "groups": "groups",
}


def load_catalogs():
    data = gm.load_from_excel(gm.DEFAULT_XLSX)
    config = data["config"]
    self_owner = config.get("self_owner", "")
    repos = data["repositories"]
    self_rows = [
        r for r in repos
        if r.get("标签分类") or str(r.get("name", "")).startswith(self_owner + "/")
    ]
    # 明细表 groups 列展示派生组（手填 + platform + topic + visibility，TSK-008）
    display = []
    for r in repos:
        row = dict(r)
        row["groups"] = ",".join(gm.build_groups(config, row, None))
        display.append(row)
    return display, self_rows


def render_table(rows, columns):
    lines = ["| " + " | ".join(HEADER[c] for c in columns) + " |",
             "| " + " | ".join(["---"] * len(columns)) + " |"]
    for r in rows:
        cells = [str(r.get(c, "")).replace("|", "\\|") or " " for c in columns]
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def render():
    repos, self_rows = load_catalogs()
    lines = [
        "# Repository Catalog",
        "",
        "Generated by `tools/catalog_to_markdown.py` from `catalogs/manifests.xlsx` - do not edit by hand.",
        "Attributes are maintained in the Excel workbook (self rows are refreshed by"
        " `tools/sync_self_repos.py`).",
        "",
    ]
    if self_rows:
        rows = sorted(self_rows, key=lambda r: (r.get("标签分类", ""), r.get("path", "")))
        lines.append(f"## 自有仓库分类与建议动作 ({len(rows)})")
        lines.append("")
        lines += render_table(rows, CLASSIFY_COLUMNS)
        lines.append("")
    rows = sorted(repos, key=lambda r: (r.get("platform", ""), r.get("path", "")))
    lines.append(f"## 清单明细 ({len(rows)})")
    lines.append("")
    lines += render_table(rows, DETAIL_COLUMNS)
    lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main():
    ap = argparse.ArgumentParser(description="Render manifests.xlsx to Markdown tables")
    ap.add_argument("--check", action="store_true",
                    help="verify docs/catalog.md is up to date instead of writing it")
    args = ap.parse_args()
    content = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if content != current:
            sys.exit("docs/catalog.md is out of date; run: python3 tools/catalog_to_markdown.py")
        print("docs/catalog.md is up to date")
        return
    OUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({content.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
