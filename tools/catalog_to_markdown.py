#!/usr/bin/env python3
"""Convert catalogs/*.json into a Markdown document of tables.

Each catalog renders two tables when data is available:
- 分类与建议动作: path / category / visibility / description / suggested_action
- 清单明细: path / name / branch / topic / language / platform / groups / protocol

Default writes docs/catalog.md; pass --check to verify the generated file
is up to date (exit non-zero when stale).
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG_DIR = ROOT / "catalogs"
OUT = ROOT / "docs" / "catalog.md"

CLASSIFY_COLUMNS = ["path", "category", "visibility", "description", "suggested_action"]
DETAIL_COLUMNS = ["path", "name", "branch", "topic", "language", "platform", "groups"]
HEADER = {
    "path": "path", "category": "分类", "visibility": "可见性",
    "description": "描述", "suggested_action": "建议动作",
    "name": "name", "branch": "branch", "topic": "topic",
    "language": "language", "platform": "platform", "groups": "groups",
}


def load_catalogs():
    for catalog_path in sorted(CATALOG_DIR.glob("*.json")):
        data = json.loads(catalog_path.read_text(encoding="utf-8"))
        yield catalog_path.stem, data.get("repositories", [])


def render_table(rows, columns):
    lines = ["| " + " | ".join(HEADER[c] for c in columns) + " |",
             "| " + " | ".join(["---"] * len(columns)) + " |"]
    for r in rows:
        cells = [str(r.get(c, "")).replace("|", "\\|") or " " for c in columns]
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def render():
    lines = [
        "# Repository Catalog",
        "",
        "Generated by `tools/catalog_to_markdown.py` from `catalogs/*.json` - do not edit by hand.",
        "Attributes are maintained by `tools/enrich_catalog.py` (category/visibility/"
        "description/suggested_action).",
        "",
    ]
    for stem, repos in load_catalogs():
        lines.append(f"## {stem} ({len(repos)} repos)")
        lines.append("")
        if any(r.get("category") for r in repos):
            rows = sorted(repos, key=lambda r: (r.get("category", ""), r.get("path", "")))
            lines.append(f"### 分类与建议动作 ({len(rows)})")
            lines.append("")
            lines += render_table(rows, CLASSIFY_COLUMNS)
            lines.append("")
        rows = sorted(repos, key=lambda r: r.get("path", ""))
        lines.append(f"### 清单明细 ({len(rows)})")
        lines.append("")
        lines += render_table(rows, DETAIL_COLUMNS)
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main():
    ap = argparse.ArgumentParser(description="Convert catalogs/*.json to Markdown tables")
    ap.add_argument("--check", action="store_true",
                    help="verify docs/catalog.md is up to date instead of writing it")
    args = ap.parse_args()
    content = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if content != current:
            sys.exit("docs/catalog.md is out of date; run: python3 tools/catalog_to_markdown.py")
        print("docs/catalog.md is up to date")
        return
    OUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({content.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
